import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

import {
  detectBlockquoteTone,
  isNumericCellText,
  normalizeMarkdownInput,
  sanitizeMarkdownUrl,
  splitCitationTokens,
} from '../src/components/assistant/markdownUtils.ts';
import {
  normalizeCodeLanguage,
  tokenizeCode,
} from '../src/components/assistant/codeHighlight.ts';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const SRC_DIR = path.resolve(__dirname, '..', 'src');

function renderGfmToHtml(markdown: string): string {
  const normalized = normalizeMarkdownInput(markdown);
  return renderToStaticMarkup(
    React.createElement(
      ReactMarkdown,
      {
        remarkPlugins: [remarkGfm],
        urlTransform: (url: string) => sanitizeMarkdownUrl(url) ?? '',
      },
      normalized
    )
  );
}

describe('Markdown Assistant - URL Sanitization & Security Guards', () => {
  it('accepts safe http, https, mailto, hash and root-relative links only', () => {
    assert.equal(sanitizeMarkdownUrl('https://example.com/docs'), 'https://example.com/docs');
    assert.equal(sanitizeMarkdownUrl('http://localhost:5173/test'), 'http://localhost:5173/test');
    assert.equal(sanitizeMarkdownUrl('mailto:support@musictrack.app'), 'mailto:support@musictrack.app');
    assert.equal(sanitizeMarkdownUrl('#section-1'), '#section-1');
    assert.equal(sanitizeMarkdownUrl('/dashboard'), '/dashboard');
  });

  it('rejects unsafe URL schemes and protocol-relative URLs', () => {
    assert.equal(sanitizeMarkdownUrl('javascript:alert(1)'), null);
    assert.equal(sanitizeMarkdownUrl('JAVASCRIPT:alert(1)'), null);
    assert.equal(sanitizeMarkdownUrl('data:text/html,<script>alert(1)</script>'), null);
    assert.equal(sanitizeMarkdownUrl('vbscript:msgbox(1)'), null);
    assert.equal(sanitizeMarkdownUrl('//evil.example.com/phish'), null);
    assert.equal(sanitizeMarkdownUrl('   '), null);
    assert.equal(sanitizeMarkdownUrl(null), null);
  });

  it('does not use dangerouslySetInnerHTML or rehype-raw anywhere in assistant components', () => {
    const files = [
      path.join(SRC_DIR, 'components', 'assistant', 'MarkdownMessage.tsx'),
      path.join(SRC_DIR, 'components', 'assistant', 'AssistantMessageItem.tsx'),
      path.join(SRC_DIR, 'components', 'analytics', 'CodebaseAssistantSection.tsx'),
    ];
    for (const file of files) {
      const code = fs.readFileSync(file, 'utf-8');
      assert.equal(code.includes('dangerouslySetInnerHTML'), false, `Forbidden dangerouslySetInnerHTML in ${file}`);
      assert.equal(code.includes('rehype-raw'), false, `Forbidden rehype-raw in ${file}`);
    }
  });
});

describe('Markdown Assistant - Utilities, Blockquotes, Citations & Syntax Tokenizer', () => {
  it('detects blockquote semantic tone and readable text label', () => {
    assert.deepEqual(
      detectBlockquoteTone('Note: Similarity scores are estimates generated by KNN.'),
      { tone: 'note', label: 'Ghi chú' }
    );
    assert.deepEqual(
      detectBlockquoteTone('Lưu ý: Thời lượng là ước tính.'),
      { tone: 'note', label: 'Ghi chú' }
    );
    assert.deepEqual(
      detectBlockquoteTone('Cảnh báo: Dữ liệu chưa đồng bộ đủ.'),
      { tone: 'warning', label: 'Cảnh báo' }
    );
    assert.deepEqual(
      detectBlockquoteTone('Important: Synchronization runs periodically.'),
      { tone: 'important', label: 'Quan trọng' }
    );
  });

  it('splits inline [S1] citation tokens accurately without breaking surrounding text', () => {
    const segments = splitCitationTokens('Hệ thống mã hóa token [S1] và chống trùng [S2].');
    assert.deepEqual(segments, [
      { type: 'text', value: 'Hệ thống mã hóa token ' },
      { type: 'citation', citationId: 'S1', raw: '[S1]' },
      { type: 'text', value: ' và chống trùng ' },
      { type: 'citation', citationId: 'S2', raw: '[S2]' },
      { type: 'text', value: '.' },
    ]);
  });

  it('identifies numeric metric table cells for tabular alignment', () => {
    assert.equal(isNumericCellText('64'), true);
    assert.equal(isNumericCellText('92.2%'), true);
    assert.equal(isNumericCellText('+24.4%'), true);
    assert.equal(isNumericCellText('311 lượt'), true);
    assert.equal(isNumericCellText('Song A'), false);
    assert.equal(isNumericCellText('Artist A'), false);
  });

  it('tokenizes Python code blocks linearly and preserves exact original source', () => {
    const sample = 'def calculate_similarity(track_a, track_b):\n    # cosine score\n    return 0.922\n';
    assert.equal(normalizeCodeLanguage('py'), 'python');
    const tokens = tokenizeCode(sample, 'python');
    assert.ok(tokens.some((t) => t.kind === 'keyword' && t.value === 'def'));
    assert.ok(tokens.some((t) => t.kind === 'comment' && t.value.includes('cosine')));
    assert.ok(tokens.some((t) => t.kind === 'number' && t.value === '0.922'));
    assert.equal(tokens.map((t) => t.value).join(''), sample);
  });
});

describe('Markdown Assistant - Representative Test Cases A, B, C, D', () => {
  it('Test Case A: renders Music Insights with headings, GFM table, bullet list, and blockquote note', () => {
    const md = [
      '## Your Listening Insights',
      '',
      'You played **230 tracks** during the selected period.',
      '',
      '### Top Tracks',
      '',
      '| Song | Artist | Plays | Similarity |',
      '|---|---|---:|---:|',
      '| Song A | Artist A | 64 | 92.2% |',
      '| Song B | Artist B | 42 | 90.8% |',
      '',
      '### Observations',
      '',
      '- Your listening activity increased.',
      '- You frequently listen to energetic tracks.',
      '- Your most active period is in the evening.',
      '',
      '> Note: Similarity scores are estimates generated by the KNN model, not actual listening statistics.',
    ].join('\n');

    const html = renderGfmToHtml(md);
    assert.ok(html.includes('<h2>Your Listening Insights</h2>'));
    assert.ok(html.includes('<strong>230 tracks</strong>'));
    assert.ok(html.includes('<table>'));
    assert.ok(html.includes('<thead>'));
    assert.ok(html.includes('<th>Song</th>'));
    assert.ok(html.includes('<td style="text-align:right">92.2%</td>'));
    assert.ok(html.includes('<ul>'));
    assert.ok(html.includes('<blockquote>'));
  });

  it('Test Case B: renders Website Support with ordered list, emphasis, and safe link', () => {
    const md = [
      '## How to synchronize Spotify',
      '',
      '1. Open your MusicTrack account.',
      '2. Select **Synchronize Spotify**.',
      '3. Wait for the synchronization to complete.',
      '',
      '**Important:** Your Spotify listening history is collected according to the application\'s supported synchronization mechanism.',
      '',
      'For more information, see the [MusicTrack documentation](https://example.com).',
    ].join('\n');

    const html = renderGfmToHtml(md);
    assert.ok(html.includes('<ol>'));
    assert.ok(html.includes('<li>Open your MusicTrack account.</li>'));
    assert.ok(html.includes('<strong>Synchronize Spotify</strong>'));
    assert.ok(html.includes('href="https://example.com/"'));
  });

  it('Test Case C: renders fenced Python code block preserving indentation', () => {
    const md = [
      '```python',
      'def calculate_similarity(track_a, track_b):',
      '    return cosine_similarity(track_a, track_b)',
      '```',
    ].join('\n');

    const html = renderGfmToHtml(md);
    assert.ok(html.includes('<pre><code class="language-python">'));
    assert.ok(html.includes('    return cosine_similarity(track_a, track_b)'));
  });

  it('Test Case D: handles malformed, incomplete, empty, long, and unsafe Markdown without crashing', () => {
    // 1. Unfinished table
    const unfinishedTable = '| Song | Artist |\n|---|---|\n| Song A |';
    assert.doesNotThrow(() => renderGfmToHtml(unfinishedTable));

    // 2. Unclosed code fence auto-closed cleanly
    const unclosedFence = '```python\ndef broken_fn():\n    return 1';
    const normalizedFence = normalizeMarkdownInput(unclosedFence);
    assert.ok(normalizedFence.endsWith('\n```'));
    const fenceHtml = renderGfmToHtml(unclosedFence);
    assert.ok(fenceHtml.includes('<pre><code class="language-python">'));

    // 3. Missing closing formatting markers
    const missingMarkers = 'Here is **unclosed bold and _unclosed italic and `unclosed code';
    const markerHtml = renderGfmToHtml(missingMarkers);
    assert.ok(markerHtml.includes('unclosed bold'));

    // 4. Empty content
    assert.equal(normalizeMarkdownInput(''), '');
    assert.equal(normalizeMarkdownInput('   \n  '), '');
    assert.equal(normalizeMarkdownInput(undefined), '');

    // 5. Very long response
    const veryLong = Array.from({ length: 200 }, (_, i) => `- Track item #${i}: **Song ${i}**`).join('\n');
    const longHtml = renderGfmToHtml(veryLong);
    assert.ok(longHtml.includes('Track item #199'));

    // 6. Unsafe link and raw script injection
    const unsafeMd =
      'Click [bad link](javascript:alert(1)) and <script>window.__xss=1</script> and ~~old~~';
    const unsafeHtml = renderGfmToHtml(unsafeMd);
    assert.equal(unsafeHtml.includes('javascript:'), false);
    assert.equal(unsafeHtml.includes('<script>'), false);
    assert.ok(unsafeHtml.includes('&lt;script&gt;'));
    assert.ok(unsafeHtml.includes('<del>old</del>'));
  });
});

